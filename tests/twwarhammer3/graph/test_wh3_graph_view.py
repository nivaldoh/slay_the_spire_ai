"""Hand-computed records for the owner-agreed graph view check (2026-11-01).

Like graph-robots/graph-as-policy tests/runtime/test_executor.py at 71549e1,
materialize a tiny graph and state the expected path. These are reader cases,
not a live effect check or a reference generated by the graph executor.
"""

import json
from copy import deepcopy

import pytest

from twwarhammer3.battle import graph, graph_view


def recorded(tmp_path):
    episode = tmp_path / "job" / "episode-0000"
    episode.mkdir(parents=True)
    def spec(unit, point):
        return {"version": graph.VERSION, "entry": "act", "nodes": {
            "act": {"op": "move", "inputs": {"units": [unit], "point": {"x": point, "z": 0}},
                    "next": {"succeeded": "done", "failed": "act", "cancelled": "done"}},
            "done": {"op": "end", "inputs": {}, "next": {}}}}
    graphs = {"line": spec("u", 20), "cavalry": spec("v", 40)}
    config = {"type": "team", "members": {
        name: {"unit_types": ["foot"] if name == "line" else None,
               "controller": {"type": "graph", "graph": value}}
        for name, value in graphs.items()}}
    result = {"battle": "battle-A", "status": "lost", "card": {
        "source_revision": "recorded-revision", "disclosure": {
            "configuration": config, "configuration_sha256": graph.digest(config)}}}
    def source(seq, ms):
        return {"battle": "battle-A", "seq": seq, "time_ms": ms}
    def observation(seq, ms, x):
        return {"kind": "observation", "observation": {
            **source(seq, ms), "phase": "Deployed", "friendly": [
                {"id": "u", "type": "foot", "x": x, "z": 0, "men": 10, "state": []},
                {"id": "v", "type": "cavalry", "x": 0, "z": 5, "men": 10, "state": []}],
            "enemy": [{"id": "e", "type": "enemy", "x": 60, "z": 0, "men": 10}]}}
    def node(member, kind, seq=1, ms=1000, **fields):
        return {"kind": "team", "event": "member_event", "member": member, "record": {
            "event": kind, "node": "act", "node_run": 1, "source": source(seq, ms),
            "graph_sha256": graph.digest(graphs[member]), **fields}}
    rows = [observation(1, 1000, 0),
            node("line", "started", op="move", inputs={"units": ["u"], "point": {"x": 20, "z": 0}}),
            node("cavalry", "started", op="move", inputs={
                "units": ["v"], "point": {"x": 40, "z": 0}}),
            {"kind": "decision", "seq": 2, "time_ms": 1500, "decision_time_ms": 1500,
             "request": "request-1", "behavior": {"member": "line", "node": "act",
                 "graph_sha256": graph.digest(graphs["line"]), "source_seq": 1, "source_ms": 1000},
             "orders": [{"unit": "u", "type": "move", "x": 20, "z": 0}]},
            {"kind": "ack", "request": "request-1", "ack": {
                "request": "request-1", "based_on": 2, "applied_ms": 1600,
                "results": [{"index": 1, "unit": "u", "ok": True}]}},
            observation(3, 3000, 20),
            node("line", "transition", 3, 3000, status="succeeded", successor="done",
                 outputs={}, witness="inside arrival radius"),
            node("cavalry", "transition", 3, 3000, status="failed", successor="act",
                 outputs={}, witness="deadline without effect witness")]
    (episode / "result.json").write_text(json.dumps(result))
    (episode / "trace.jsonl").write_text("\n".join(map(json.dumps, rows)) + "\n")
    return episode, result, rows


def rewrite(episode, result, rows):
    (episode / "result.json").write_text(json.dumps(result))
    (episode / "trace.jsonl").write_text("\n".join(map(json.dumps, rows)) + ("\n" if rows else ""))


def test_source_time_dispatch_and_ack_are_separate_from_completion(tmp_path):
    episode, _, _ = recorded(tmp_path)
    value = graph_view.collect_episode(episode)
    line = [e for e in value["events"] if e["member"] == "line"]
    assert [e["kind"] for e in line] == ["started", "orders", "ack", "transition"]
    order, ack, done = line[1:]
    assert order["time_ms"] == 1500 and order["source"]["time_ms"] == 1000
    assert ack["time_ms"] == 1600 and "status" not in ack and "witness" not in ack
    assert done["time_ms"] == 3000 and done["status"] == "succeeded"
    assert done["inputs"] == {"units": ["u"], "point": {"x": 20, "z": 0}}
    assert done["line"] == 7 and done["source"]["seq"] == 3
    assert value["source_revision"] == "recorded-revision"


def test_same_node_and_run_in_different_members_do_not_share_inputs(tmp_path):
    episode, _, _ = recorded(tmp_path)
    value = graph_view.collect_episode(episode)
    finished = {e["member"]: e for e in value["events"] if e["kind"] == "transition"}
    assert finished["line"]["inputs"]["units"] == ["u"]
    assert finished["cavalry"]["inputs"]["units"] == ["v"]
    assert finished["cavalry"]["status"] == "failed"
    assert finished["cavalry"]["witness"] == "deadline without effect witness"


def test_delayed_event_keeps_original_source_and_does_not_appear_before_collection(tmp_path):
    episode, result, rows = recorded(tmp_path)
    rows.insert(1, deepcopy(rows[5]))  # The 3 s observation arrives before the old node event.
    rewrite(episode, result, rows)
    started = graph_view.collect_episode(episode)["events"][0]
    assert started["time_ms"] == 3000
    assert started["source"] == {"battle": "battle-A", "seq": 1, "time_ms": 1000}


def test_stale_or_unknown_source_reference_is_not_a_valid_map_time(tmp_path):
    episode, result, rows = recorded(tmp_path)
    rows[1]["record"]["source"]["time_ms"] = 1200
    rewrite(episode, result, rows)
    with pytest.raises(ValueError, match="matching public source"):
        graph_view.collect_episode(episode)


@pytest.mark.parametrize("change,match", [
    ("configuration", "configuration"), ("graph", "member's recorded graph"),
    ("member", "member's recorded graph"), ("battle", "different battle"),
    ("successor", "recorded exit"), ("start", "matching member/node run"),
    ("ack_unit", "acknowledgement"), ("ack_request", "acknowledgement"),
    ("ack_seq", "acknowledgement"),
])
def test_wrong_record_mapping_is_rejected(tmp_path, change, match):
    episode, result, rows = recorded(tmp_path)
    if change == "configuration":
        result["card"]["disclosure"]["configuration"]["members"]["line"]["unit_types"] = None
    elif change == "graph":
        rows[1]["record"]["graph_sha256"] = "wrong-graph"
    elif change == "member":
        rows[1]["member"] = "cavalry"
    elif change == "battle":
        rows[1]["record"]["source"]["battle"] = "another-battle"
    elif change == "successor":
        rows[6]["record"]["successor"] = "act"
    elif change == "start":
        rows[6]["record"]["node_run"] = 2
    elif change == "ack_unit":
        rows[4]["ack"]["results"][0]["unit"] = "v"
    elif change == "ack_request":
        rows[4]["ack"]["request"] = "another-request"
    else:
        rows[4]["ack"]["based_on"] = 1  # Original member source, not root dispatch seq 2.
    rewrite(episode, result, rows)
    with pytest.raises(ValueError, match=match):
        graph_view.collect_episode(episode)


def test_hidden_blocks_are_not_in_map_or_event_data(tmp_path):
    episode, result, rows = recorded(tmp_path)
    before = graph_view.collect_episode(episode)
    for row in rows:
        row.update(evaluation={"enemy": "hidden-diagnostic"}, setup="secret", final="hidden-end")
        if row["kind"] == "observation":
            row["observation"].update(evaluation={"enemy": "hidden-position"}, final="hidden")
            row["observation"]["friendly"][0]["target"] = "hidden-target"
    rewrite(episode, result, rows)
    after = graph_view.collect_episode(episode)
    before.pop("evidence")  # Raw file hashes must change.
    after.pop("evidence")
    assert after == before
    assert "hidden" not in json.dumps(after)


def test_local_cancel_is_not_a_success_and_empty_ack_has_no_completion(tmp_path):
    episode, result, rows = recorded(tmp_path)
    rows[6]["record"].update(event="cancelled", reason="local cancellation; no stop order sent")
    rows[6]["record"].pop("status")
    rows[4]["ack"]["results"] = []
    rewrite(episode, result, rows)
    events = graph_view.collect_episode(episode)["events"]
    assert not any(e.get("status") == "succeeded" for e in events)
    assert next(e for e in events if e["kind"] == "ack")["ack"]["results"] == []
    assert "no stop order" in next(e for e in events if e["kind"] == "cancelled")["reason"]


def test_render_escapes_data_and_does_not_expand_tokens_from_recorded_text(tmp_path):
    episode, result, rows = recorded(tmp_path)
    rows[6]["record"]["witness"] = "</script><script>bad()</script> /* GRAPH_VIEW_JS */"
    rewrite(episode, result, rows)
    page = graph_view.render(graph_view.collect([episode]))
    assert "</script><script>bad()" not in page
    assert "\\u003c/script>" in page
    assert "/* GRAPH_VIEW_JS */" in page  # The data string is not another template expansion.


def test_job_expansion_and_write_preserve_inputs(tmp_path):
    episode, _, _ = recorded(tmp_path)
    hashes = [p.read_bytes() for p in (episode / "result.json", episode / "trace.jsonl")]
    output = tmp_path / "view.html"
    assert graph_view.write([episode.parent], output) == output
    assert "Watch a graph control its units" in output.read_text()
    assert hashes == [p.read_bytes() for p in (episode / "result.json", episode / "trace.jsonl")]
    with pytest.raises(ValueError, match="duplicate"):
        graph_view.collect([episode, episode.parent])
    with pytest.raises(ValueError, match="end in .html"):
        graph_view.write([episode], episode / "trace.jsonl")
    with pytest.raises(ValueError, match="needs saved"):
        graph_view.collect([tmp_path / "missing"])


def test_root_graph_uses_its_own_events_without_a_team_wrapper(tmp_path):
    episode, result, rows = recorded(tmp_path)
    disclosure = result["card"]["disclosure"]
    config = disclosure["configuration"]["members"]["line"]["controller"]
    disclosure.update(configuration=config, configuration_sha256=graph.digest(config))
    rows = [r for r in rows if r.get("member") != "cavalry"]
    for row in rows:
        if row.get("kind") == "team":
            value = row.pop("record")
            row.pop("member")
            row.update(value)
        if row.get("kind") == "decision":
            row["behavior"].pop("member")
    rewrite(episode, result, rows)
    value = graph_view.collect_episode(episode)
    assert set(value["graphs"]) == {"army"}
    assert {e["member"] for e in value["events"]} == {"army"}
    assert value["events"][-1]["witness"] == "inside arrival radius"


def test_graph_view_cli_reads_saved_episode_only(tmp_path, monkeypatch, capsys):
    from twwarhammer3.__main__ import main

    episode, _, _ = recorded(tmp_path)
    output = tmp_path / "viewer.html"
    monkeypatch.setattr("sys.argv", ["twwarhammer3", "graph-view", str(episode),
                                     "--output", str(output)])
    assert main() == 0 and output.is_file()
    assert capsys.readouterr().out.strip() == str(output)


@pytest.mark.parametrize("recording", ["empty", "observations_only", "non_graph"])
def test_missing_graph_execution_does_not_write_an_unusable_view(tmp_path, recording):
    episode, result, rows = recorded(tmp_path)
    rows = [] if recording == "empty" else [rows[0]]
    if recording == "non_graph":
        config = {"type": "hold"}
        result["card"]["disclosure"].update(
            configuration=config, configuration_sha256=graph.digest(config))
    rewrite(episode, result, rows)
    output = tmp_path / "view.html"
    with pytest.raises(ValueError, match="no recorded public frames or graph execution"):
        graph_view.write([episode], output)
    assert not output.exists()


def test_terminal_result_observation_bounds_later_closure_and_map(tmp_path):
    episode, result, rows = recorded(tmp_path)
    terminal = deepcopy(rows[5])
    terminal["kind"] = "result"
    terminal["observation"].update(seq=4, time_ms=4000, result="lost")
    closed = deepcopy(rows[1])
    closed["record"]["event"] = "closed"  # Its source remains the older 1000 ms view.
    rows.extend([terminal, closed])
    rewrite(episode, result, rows)
    value = graph_view.collect_episode(episode)
    assert value["frames"][-1]["seq"] == 4 and value["frames"][-1]["time_ms"] == 4000
    assert value["events"][-1]["kind"] == "closed"
    assert value["events"][-1]["time_ms"] == 4000
    assert value["events"][-1]["source"]["time_ms"] == 1000


def test_partial_batch_acknowledgement_keeps_the_missing_result_explicit(tmp_path):
    episode, result, rows = recorded(tmp_path)
    rows[3]["orders"].append({"unit": "u", "type": "move", "x": 25, "z": 0, "queue": True})
    rewrite(episode, result, rows)
    ack = next(e for e in graph_view.collect_episode(episode)["events"] if e["kind"] == "ack")
    assert ack["orders_expected"] == 2
    assert ack["missing_result_indexes"] == [2]
    assert ack["ack"]["results"] == [{"index": 1, "unit": "u", "ok": True}]


def referenced_recording(tmp_path):
    episode, result, rows = recorded(tmp_path)
    disclosure = result["card"]["disclosure"]
    config = disclosure["configuration"]
    spec = config["members"]["line"]["controller"]["graph"]
    spec["entry"] = "find"
    spec["nodes"]["find"] = {"op": "owned", "inputs": {}, "next": {
        "succeeded": "act", "empty": "find"}}
    spec["nodes"]["act"]["inputs"]["units"] = {"ref": "find.units"}
    revision = graph.digest(spec)
    disclosure["configuration_sha256"] = graph.digest(config)
    for row in rows:
        if row.get("member") == "line":
            row["record"]["graph_sha256"] = revision
        if row.get("kind") == "decision":
            row["behavior"]["graph_sha256"] = revision
    proof = {"producer": "find", "node_run": 1, "graph_sha256": revision,
             "battle": "battle-A", "seq": 1, "time_ms": 1000, "value": ["u"]}
    rows[1]["record"]["input_sources"] = {"units": proof}
    started = {"kind": "team", "event": "member_event", "member": "line", "record": {
        "event": "started", "node": "find", "op": "owned", "node_run": 1,
        "graph_sha256": revision, "source": {"battle": "battle-A", "seq": 1, "time_ms": 1000},
        "inputs": {}}}
    finished = deepcopy(started)
    finished["record"].update(event="transition", status="succeeded", successor="act",
                               outputs={"units": ["u"]})
    rows[1:1] = [started, finished]
    rewrite(episode, result, rows)
    return episode, result, rows, proof


def test_referenced_input_matches_its_actual_producer_record(tmp_path):
    episode, _, _, proof = referenced_recording(tmp_path)
    value = graph_view.collect_episode(episode)
    started = next(e for e in value["events"] if e["kind"] == "started" and e["node"] == "act")
    assert started["input_sources"]["units"] == proof
    assert started["inputs"]["units"] == ["u"]


@pytest.mark.parametrize("field,value", [
    ("battle", "foreign-battle"), ("graph_sha256", "foreign-graph"),
    ("producer", "another-node"), ("node_run", 9), ("seq", 3), ("value", ["v"]),
])
def test_foreign_or_misbound_nested_input_source_is_rejected(tmp_path, field, value):
    episode, result, rows, proof = referenced_recording(tmp_path)
    proof[field] = value
    rewrite(episode, result, rows)
    with pytest.raises(ValueError, match="input source"):
        graph_view.collect_episode(episode)
