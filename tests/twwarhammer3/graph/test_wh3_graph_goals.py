def test_queries_obey_battle_time_spacing_and_none_clears_a_previous_hint(tmp_path):
    sender = Canned()
    policy = controller(tmp_path, sender)
    policy.max_requests = 2
    try:
        policy.decide(state())
        finish_request(policy, sender)
        policy.decide(state(2, 1100))
        policy.decide(state(3, 30999))
        assert policy.counter == 1 and policy.hint["target"] == "far"
        sender.target = "none"
        policy.decide(state(4, 31000))
        policy.pending[1].result(timeout=2)
        policy.decide(state(5, 31100))
        assert policy.counter == 2 and len(sender.requests) == 2 and policy.hint is None
        assert sender.requests[-1]["goal_source"]["node_run"] == 2
    finally:
        sender.release.set()
        policy.close()


