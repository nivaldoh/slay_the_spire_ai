"""Canned goal requests over hand-computed graph paths; no game or real HTTP.

Reference: gap-plan's independent progress/public information contract. Like GaP's
tests/runtime/test_executor.py at 71549e1, use a small graph and explicit expected
outputs, not a saved result generated by this controller.
Timing and size examples rest on JUDGEMENT graph_goals.py G4 Goal limits.
"""

import json
from concurrent.futures import Future
from threading import Event, Thread

import pytest

from gameai.ledger import BudgetExhausted, Ledger
from gameai.llm import InvalidReply, Model
from twwarhammer3.battle import graph, graph_goals, team
from twwarhammer3.protocol import PolicyFailure


def state(seq=1, ms=1000):
    return {"battle": "battle-A", "seq": seq, "time_ms": ms, "phase": "Deployed",
            "friendly": [{"id": "u", "type": "foot", "x": 0, "z": 0,
                          "men": 10, "state": []}],
            "enemy": [{"id": "near", "x": 10, "z": 0, "men": 10, "state": []},
                      {"id": "far", "x": 50, "z": 0, "men": 10, "state": []}]}


def spec(mode="nearest"):
    return {"version": graph.VERSION, "entry": "owned", "nodes": {
        "owned": {"op": "owned", "inputs": {},
                  "next": {"succeeded": "pick", "empty": "owned"}},
        "pick": {"op": "select_target", "mode": mode,
                 "inputs": {"units": {"ref": "owned.units"}},
                 "next": {"succeeded": "act", "empty": "owned"}},
        "act": {"op": "engage", "inputs": {"units": {"ref": "owned.units"},
                                               "target": {"ref": "pick.target"}},
                "next": {"succeeded": "owned", "failed": "owned", "cancelled": "owned"}}}}


class Canned:
    def __init__(self, target="far", *, failed=False, invalid=False, reason="test"):
        self.target, self.failed, self.invalid = target, failed, invalid
        self.reason = reason
        self.entered, self.release = Event(), Event()
        self.requests = []

    def __call__(self, body):
        self.requests.append(json.loads(body["input"][0]["content"]))
        self.entered.set()
        assert self.release.wait(5), "test did not release its canned request"
        text = ("not JSON" if self.invalid
                else json.dumps({"target": self.target, "reason": self.reason}))
        return {"id": "canned-goal", "status": "failed" if self.failed else "completed",
                "usage": {"input_tokens": 0, "output_tokens": 0},
                "error": {"code": "server_error"} if self.failed else None,
                "output": [{"type": "message", "content": [
                    {"type": "output_text", "text": text}]}]}


def controller(tmp_path, sender, *, mode="nearest", budget=1, stop=None):
    ledger = Ledger(tmp_path / "test-ledger.jsonl", budget)
    api = Model("claude-haiku-5-5", "low", ledger, instructions=graph_goals.PROMPT_PATH.read_text(),
                max_output_tokens=graph_goals.MAX_OUTPUT_TOKENS, provider="anthropic",
                send=sender, record_exchanges=True)
    return graph_goals.GraphGoals(spec(mode), api, max_requests=1, stop=stop)


def finish_request(policy, sender):
    assert sender.entered.wait(2)
    sender.release.set()
    policy.pending[1].result(timeout=2)


def test_graph_keeps_acting_and_hint_applies_only_at_the_next_selection(tmp_path):
    sender = Canned()
    policy = controller(tmp_path, sender)
    try:
        policy.decide(state())  # owned; starts a held goal request
        assert sender.entered.wait(2)
        policy.decide(state(2, 1100))  # nearest target, without waiting for that request
        orders = policy.decide(state(3, 1200))
        assert orders[0]["target"] == "near" and not sender.release.is_set()
        finish_request(policy, sender)
        melee = state(4, 1300)
        melee["friendly"][0].update(target="near", state=["melee"])
        assert policy.decide(melee) == []  # existing action completes on its own witness
        assert policy.hint["target"] == "far"
        policy.decide(state(5, 1400))  # refresh units
        policy.decide(state(6, 1500))  # new target selection consumes eligible hint
        assert policy.decide(state(7, 1600))[0]["target"] == "far"
        selected = [e for e in policy.drain_events()
                    if e.get("event") == "transition" and e.get("node") == "pick"][-1]
        hint = selected["selection"]["preference"]
        assert selected["selection"]["used"] is True
        assert hint["source"]["seq"] == 1 and hint["source"]["node_run"] == 1
        assert hint["source"]["producer"] == "goal_request"
        assert hint["source"]["controller"] == policy.controller
        assert selected["source"]["seq"] == 6 and len(sender.requests) == 1
    finally:
        sender.release.set()
        policy.close()


def test_goal_input_uses_only_the_existing_public_member_projection(tmp_path):
    sender = Canned()
    policy = controller(tmp_path, sender)
    view = state()
    view.update(evaluation={"enemy": "hidden-value"}, final="private-final", setup="private-setup")
    view["allies"] = [{"id": "ally", "x": 1, "z": 1, "men": 10, "state": [],
                       "command_queue": "private-queue", "notes": "private-plan"}]
    try:
        policy.decide(view)
        assert sender.entered.wait(2)
        prompt = json.dumps(sender.requests[0])
        for secret in ("hidden-value", "private-final", "private-setup",
                       "private-queue", "private-plan"):
            assert secret not in prompt
        assert sender.requests[0]["candidates"] == ["far", "near"]
        assert sender.requests[0]["observation"]["friendly"][0]["id"] == "u"
        assert sender.requests[0]["observation"]["allies"][0]["id"] == "ally"
    finally:
        sender.release.set()
        policy.close()


@pytest.mark.parametrize("change,reason", [
    ("expired", "expired"), ("ownership", "ownership"), ("hidden", "eligible"),
])
def test_stale_reply_never_publishes_a_hint(tmp_path, change, reason):
    sender = Canned()
    policy = controller(tmp_path, sender)
    try:
        policy.decide(state())
        assert sender.entered.wait(2)
        current = state(2, 1100)
        if change == "expired":
            current["time_ms"] = 1000 + graph_goals.HINT_MS
        elif change == "ownership":
            current["friendly"].append({"id": "new", "x": 0, "z": 1, "men": 10, "state": []})
        else:
            current["enemy"] = [current["enemy"][0]]
        policy.decide(current)
        finish_request(policy, sender)
        current.update(seq=3, time_ms=current["time_ms"] + 100)
        orders = policy.decide(current)
        assert policy.hint is None and orders[0]["target"] == "near"
        discarded = [e for e in policy.drain_events() if e["event"] == "goal_discarded"]
        assert discarded and reason in discarded[-1]["reason"]
    finally:
        sender.release.set()
        policy.close()


def test_target_preference_cannot_override_a_selectors_engaged_mode():
    hint = {"target": "far", "source": {"node_run": 1}}
    policy = graph.GraphPolicy(spec("engaged"), target_preference=lambda view: hint)
    view = state()
    view["enemy"][0]["state"] = ["melee"]
    policy.decide(view)
    view.update(seq=2, time_ms=1100)
    policy.decide(view)
    assert policy.values["pick.target"]["value"] == "near"
    selected = [e for e in policy.drain_events() if e.get("node") == "pick"][-1]
    assert selected["selection"]["used"] is False


@pytest.mark.parametrize("failed", [False, True])
def test_close_discards_late_reply_retains_exchange_and_prevents_new_sends(tmp_path, failed):
    sender = Canned(failed=failed)
    policy = controller(tmp_path, sender)
    errors = []

    def close():
        try:
            policy.close()
        except Exception as exc:
            errors.append(exc)

    policy.decide(state())
    assert sender.entered.wait(2)
    closer = Thread(target=close)
    closer.start()
    try:
        assert policy.stopped.wait(2)
        sender.release.set()
        closer.join(2)
        assert not closer.is_alive() and not errors
        assert policy.hint is None and policy.graph.closed
        assert len(sender.requests) == 1  # even a failed response cannot resend after close
        exchanges = list(policy.api.drain_exchanges())
        assert len(exchanges) == 1 and exchanges[0]["attempts"]
        assert policy.api.ledger.held == 0
        assert policy.decide(state(2, 1100)) == []
    finally:
        sender.release.set()
        closer.join(2)
        policy.close()


def test_budget_stop_is_not_a_silent_fallback_or_a_gameplay_loss(tmp_path):
    sender = Canned()
    policy = controller(tmp_path, sender, budget=0)
    try:
        policy.decide(state())
        with pytest.raises(BudgetExhausted):
            policy.pending[1].result(timeout=2)
        with pytest.raises(BudgetExhausted):
            policy.decide(state(2, 1100))
        assert not sender.requests and policy.api.ledger.spent == policy.api.ledger.held == 0
    finally:
        policy.close()


def test_foreign_controller_reply_is_discarded_even_with_the_same_graph_and_battle(tmp_path):
    sender = Canned()
    policy = controller(tmp_path, sender)
    try:
        foreign = {**policy._source(state()), "controller": "another-controller", "node_run": 1}
        future = Future()
        future.set_result(({"target": "far", "reason": "foreign"}, []))
        policy.pending, policy.live_run, policy.counter = (foreign, future), 1, 1
        policy.decide(state())
        assert policy.hint is None and not sender.requests
        discarded = next(e for e in policy.drain_events() if e["event"] == "goal_discarded")
        assert "different controller" in discarded["reason"]
    finally:
        policy.close()


def test_new_episode_has_no_goal_memory_and_old_instance_refuses_reuse(tmp_path):
    sender = Canned()
    policy = controller(tmp_path, sender)
    try:
        policy.decide(state())
        finish_request(policy, sender)
        policy.decide(state(2, 1100))
        assert policy.hint is not None
        foreign = state(3, 1200)
        foreign["battle"] = "new-battle"
        with pytest.raises(PolicyFailure, match="different battle"):
            policy.decide(foreign)
        fresh = controller(tmp_path, Canned())
        try:
            assert fresh.hint is None and fresh.counter == 0
            assert fresh.graph.node == "owned" and fresh.controller != policy.controller
        finally:
            fresh.close()
    finally:
        sender.release.set()
        policy.close()


@pytest.mark.parametrize("goal_member", ["line", "cavalry"])
def test_team_and_goal_graph_both_dispatch_while_goal_reply_is_held(tmp_path, goal_member):
    sender = Canned()
    goals = controller(tmp_path, sender)
    peer = graph.GraphPolicy(spec())
    policies = {goal_member: goals, "cavalry" if goal_member == "line" else "line": peer}
    policy = team.TeamPolicy({"line": (("foot",), policies["line"]),
                              "cavalry": (("horse",), policies["cavalry"])})
    dispatched = {}
    try:
        for seq in range(1, 18):
            view = state(seq, 1000 + seq * 100)
            view["friendly"].append({"id": "c", "type": "horse", "x": 0, "z": 2,
                                     "men": 10, "state": []})
            orders = policy.decide(view)
            for member in policy.members.values():
                if member.future is not None:
                    member.future.result(timeout=1)
            if policy.selected is not None:
                name = policy.selected
                if orders:
                    dispatched[name] = orders
                policy.acknowledge({"request": str(seq), "applied_ms": view["time_ms"],
                                    "results": [{"index": i, "unit": order["unit"],
                                                 "ok": True}
                                                for i, order in enumerate(orders)]}, {})
            if len(dispatched) == 2:
                break
        assert sender.entered.wait(1) and not sender.release.is_set()
        assert {name: [o["unit"] for o in orders] for name, orders in dispatched.items()} == {
            "line": ["u"], "cavalry": ["c"]}
        assert all(o["target"] == "near" for orders in dispatched.values() for o in orders)
        assert goals.graph.run.status == peer.run.status == "running"
        assert goals.counter == 1 and len(sender.requests) == 1
    finally:
        sender.release.set()
        policy.close()
    assert len(list(policy.drain_exchanges())) == 1 and goals.api.ledger.held == 0


def test_closing_one_goal_controller_does_not_stop_its_peer(tmp_path):
    parent = Event()
    first = controller(tmp_path, Canned(), stop=parent)
    sender = Canned()
    second = controller(tmp_path, sender, stop=parent)
    try:
        first.close()
        assert not parent.is_set()
        second.decide(state())
        finish_request(second, sender)
        second.decide(state(2, 1100))
        assert second.hint["target"] == "far" and not second.stopped.is_set()
    finally:
        sender.release.set()
        second.close()


