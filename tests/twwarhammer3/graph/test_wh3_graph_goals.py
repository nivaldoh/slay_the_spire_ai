@pytest.mark.parametrize("options", [
    {"target": "not-a-candidate"}, {"reason": "x" * 201}, {"invalid": True},
])
def test_invalid_goal_reply_is_recorded_and_cannot_become_a_hint(tmp_path, options):
    sender = Canned(**options)
    policy = controller(tmp_path, sender)
    try:
        policy.decide(state())
        assert sender.entered.wait(2)
        sender.release.set()
        with pytest.raises(InvalidReply):
            policy.pending[1].result(timeout=2)
        with pytest.raises(PolicyFailure) as failure:
            policy.decide(state(2, 1100))
        assert failure.value.failure["kind"] == "invalid_reply"
        assert policy.hint is None and policy.pending is None and len(sender.requests) == 1
        assert len(list(policy.api.drain_exchanges())) == 1 and policy.api.ledger.held == 0
        assert any(e["event"] == "goal_failed" for e in policy.drain_events())
    finally:
        sender.release.set()
        policy.close()
